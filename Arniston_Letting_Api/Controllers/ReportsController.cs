using Arniston_Letting_API.Data;
using Arniston_Letting_API.DTOs.Reports;
using Arniston_Letting_API.Models;
using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Mvc;
using Microsoft.EntityFrameworkCore;

namespace Arniston_Letting_API.Controllers;

/*
 *          Controller Setup
 *
 *      [ApiController] Enables API-specific behaviour, including automatic
 *      model validation and binding of request data.
 *
 *      [Route("api/[controller]")] Sets the base route for all report
 *      endpoints to api/reports.
 *
 *      [Authorize(Roles = "Admin")] Restricts every report endpoint to
 *      users with the Admin role, consistent with all other controllers.
 *
 *      ApplicationDbContext Provides access to the application's database
 *      through Entity Framework Core.
 *
 */
[ApiController]
[Route("api/[controller]")]
[Authorize(Roles = "Admin")]
public class ReportsController : ControllerBase
{
    private readonly ApplicationDbContext _context;

    public ReportsController(ApplicationDbContext context)
    {
        _context = context;
    }

    #region Get Reports

    /*
     *          Functionality for retrieving all reports.
     *
     *      [HttpGet] Allows an HTTP GET request to retrieve all report records.
     *
     *      AsNoTracking Disables Entity Framework Core change tracking because
     *      the retrieved report records are only being read.
     *
     *      Select Projects each report into a ReportDto, returning only
     *      the required report properties.
     *
     *      OrderByDescending Sorts the reports by date, with the newest
     *      reports appearing first.
     *
     *      ToListAsync Executes the query asynchronously and retrieves
     *      the report records.
     *
     *      Returns 200 OK with the list of reports.
     *
     */
    [HttpGet]
    public async Task<ActionResult<IEnumerable<ReportDto>>> GetReports()
    {
        // Retrieve all reports without enabling change tracking.
        var reports = await _context.Reports
            .AsNoTracking()
            .Select(r => new ReportDto
            {
                ReportId = r.ReportId,
                ReportType = r.ReportType,
                Date = r.Date,
                GeneratedBy = r.GeneratedBy,
                Status = r.Status,
                Description = r.Description
            })
            .OrderByDescending(r => r.Date)
            .ToListAsync();

        // Return the retrieved reports.
        return Ok(reports);
    }

    #endregion

    #region Get Report

    /*
     *          Functionality for retrieving a report by ID.
     *
     *      [HttpGet("{id:int}")] Allows an HTTP GET request to retrieve
     *      a specific report using its integer ID.
     *
     *      AsNoTracking Disables change tracking because the report record
     *      is only being retrieved and not modified.
     *
     *      Where Filters the reports to find the record matching
     *      the supplied report ID.
     *
     *      Select Projects the matching report into a ReportDto.
     *
     *      FirstOrDefaultAsync Executes the query asynchronously and returns
     *      the matching report, or null if no record exists.
     *
     *      If the report does not exist, the endpoint returns 404 Not Found
     *      with an explanatory message.
     *
     *      Returns 200 OK with the report details when found.
     *
     */
    [HttpGet("{id:int}")]
    public async Task<ActionResult<ReportDto>> GetReport(int id)
    {
        // Find the report matching the supplied ID without enabling change tracking.
        var report = await _context.Reports
            .AsNoTracking()
            .Where(r => r.ReportId == id)
            .Select(r => new ReportDto
            {
                ReportId = r.ReportId,
                ReportType = r.ReportType,
                Date = r.Date,
                GeneratedBy = r.GeneratedBy,
                Status = r.Status,
                Description = r.Description
            })
            .FirstOrDefaultAsync();

        // Check whether the requested report exists.
        if (report == null)
        {
            return NotFound(new
            {
                message = "Report not found."
            });
        }

        // Return the report details.
        return Ok(report);
    }

    #endregion

    #region Create Report

    /*
     *          Functionality for creating a new report.
     *
     *      [HttpPost] Allows an HTTP POST request to create a report.
     *
     *      [Authorize(Roles = "Admin")] Restricts report creation to
     *      authenticated users with the Admin role.
     *
     *      CreateReportDto Receives the report details from the request body.
     *
     *      ModelState.IsValid Checks whether the supplied request data
     *      passes model validation.
     *
     *      String Processing Trims unnecessary whitespace from the report
     *      type, generated by, status and description fields.
     *
     *      Report Type Validation Ensures that the report type is not
     *      null, empty or whitespace.
     *
     *      Generated By Validation Ensures that the generated by field
     *      is not null, empty or whitespace.
     *
     *      Status Validation Ensures that the report status is not
     *      null, empty or whitespace.
     *
     *      Report Creates a new report entity using the processed
     *      request values.
     *
     *      Add Adds the new report entity to the database context.
     *
     *      SaveChangesAsync Saves the new report record to the database.
     *
     *      ReportDto Creates the response object containing the saved
     *      report details, including its generated ID.
     *
     *      Returns 400 Bad Request if the request data is invalid or
     *      any required report text field is missing.
     *
     *      Returns 201 Created with the created report and its resource
     *      location when successful.
     *
     */
    [HttpPost]
    [Authorize(Roles = "Admin")]
    public async Task<ActionResult<ReportDto>> CreateReport(
        [FromBody] CreateReportDto request)
    {
        // Validate the supplied report data.
        if (!ModelState.IsValid)
        {
            return BadRequest(ModelState);
        }

        // Remove unnecessary whitespace from the supplied report details.
        var reportType = request.ReportType?.Trim();
        var generatedBy = request.GeneratedBy?.Trim();
        var status = request.Status?.Trim();
        var description = request.Description?.Trim();

        // Ensure that the report type has been provided.
        if (string.IsNullOrWhiteSpace(reportType))
        {
            return BadRequest(new
            {
                message = "Report type is required."
            });
        }

        // Ensure that the generated by field has been provided.
        if (string.IsNullOrWhiteSpace(generatedBy))
        {
            return BadRequest(new
            {
                message = "Generated by is required."
            });
        }

        // Ensure that the report status has been provided.
        if (string.IsNullOrWhiteSpace(status))
        {
            return BadRequest(new
            {
                message = "Report status is required."
            });
        }

        // Create a new report using the processed request details.
        var report = new Report
        {
            ReportType = reportType,
            Date = request.Date,
            GeneratedBy = generatedBy,
            Status = status,
            Description = description
        };

        // Add the new report to the database context.
        _context.Reports.Add(report);

        // Save the report and generate its database ID.
        await _context.SaveChangesAsync();

        // Map the saved report into a DTO for the response.
        var result = new ReportDto
        {
            ReportId = report.ReportId,
            ReportType = report.ReportType,
            Date = report.Date,
            GeneratedBy = report.GeneratedBy,
            Status = report.Status,
            Description = report.Description
        };

        // Return 201 Created with the report details and its resource location.
        return CreatedAtAction(
            nameof(GetReport),
            new { id = report.ReportId },
            result);
    }

    #endregion

    #region Update Report

    /*
     *          Functionality for updating an existing report.
     *
     *      [HttpPut("{id:int}")] Allows an HTTP PUT request to update
     *      a report using its integer ID.
     *
     *      [Authorize(Roles = "Admin")] Restricts report updates to
     *      authenticated users with the Admin role.
     *
     *      UpdateReportDto Receives the updated report details from
     *      the request body.
     *
     *      ModelState.IsValid Checks whether the supplied request data
     *      passes model validation.
     *
     *      FirstOrDefaultAsync Searches the database for the report
     *      matching the supplied ID.
     *
     *      If the report does not exist, the endpoint returns 404 Not Found
     *      with an explanatory message.
     *
     *      String Processing Trims unnecessary whitespace from the report
     *      type, generated by, status and description fields.
     *
     *      Report Type Validation Ensures that the updated report type
     *      is not null, empty or whitespace.
     *
     *      Generated By Validation Ensures that the updated generated by
     *      field is not null, empty or whitespace.
     *
     *      Status Validation Ensures that the updated report status
     *      is not null, empty or whitespace.
     *
     *      Property Assignment Updates the existing report fields using
     *      the processed request values.
     *
     *      SaveChangesAsync Saves the updated report record to the database.
     *
     *      Returns 400 Bad Request if the request data is invalid or
     *      any required report text field is missing.
     *
     *      Returns 404 Not Found if the report does not exist.
     *
     *      Returns 204 No Content when the update is successful.
     *
     */
    [HttpPut("{id:int}")]
    [Authorize(Roles = "Admin")]
    public async Task<IActionResult> UpdateReport(
        int id,
        [FromBody] UpdateReportDto request)
    {
        // Validate the supplied report data.
        if (!ModelState.IsValid)
        {
            return BadRequest(ModelState);
        }

        // Find the report that needs to be updated.
        var report = await _context.Reports
            .FirstOrDefaultAsync(r => r.ReportId == id);

        // Check whether the requested report exists.
        if (report == null)
        {
            return NotFound(new
            {
                message = "Report not found."
            });
        }

        // Remove unnecessary whitespace from the supplied report details.
        var reportType = request.ReportType?.Trim();
        var generatedBy = request.GeneratedBy?.Trim();
        var status = request.Status?.Trim();
        var description = request.Description?.Trim();

        // Ensure that the updated report type has been provided.
        if (string.IsNullOrWhiteSpace(reportType))
        {
            return BadRequest(new
            {
                message = "Report type is required."
            });
        }

        // Ensure that the updated generated by field has been provided.
        if (string.IsNullOrWhiteSpace(generatedBy))
        {
            return BadRequest(new
            {
                message = "Generated by is required."
            });
        }

        // Ensure that the updated report status has been provided.
        if (string.IsNullOrWhiteSpace(status))
        {
            return BadRequest(new
            {
                message = "Report status is required."
            });
        }

        // Update the report fields using the processed request details.
        report.ReportType = reportType;
        report.Date = request.Date;
        report.GeneratedBy = generatedBy;
        report.Status = status;
        report.Description = description;

        // Save the updated report record to the database.
        await _context.SaveChangesAsync();

        // Return 204 No Content to indicate that the update was successful.
        return NoContent();
    }

    #endregion

    #region Delete Report

    /*
     *          Functionality for deleting an existing report.
     *
     *      [HttpDelete("{id:int}")] Allows an HTTP DELETE request to remove
     *      a report using its integer ID.
     *
     *      [Authorize(Roles = "Admin")] Restricts report deletion to
     *      authenticated users with the Admin role.
     *
     *      FirstOrDefaultAsync Searches the database for the report
     *      matching the supplied ID.
     *
     *      If the report does not exist, the endpoint returns 404 Not Found
     *      with an explanatory message.
     *
     *      Remove Marks the report entity for deletion in the database context.
     *
     *      SaveChangesAsync Applies the deletion to the database.
     *
     *      Returns 404 Not Found if the report does not exist.
     *
     *      Returns 204 No Content when the report is successfully deleted.
     *
     */
    [HttpDelete("{id:int}")]
    [Authorize(Roles = "Admin")]
    public async Task<IActionResult> DeleteReport(int id)
    {
        // Find the report that needs to be deleted.
        var report = await _context.Reports
            .FirstOrDefaultAsync(r => r.ReportId == id);

        // Check whether the requested report exists.
        if (report == null)
        {
            return NotFound(new
            {
                message = "Report not found."
            });
        }

        // Mark the report record for deletion.
        _context.Reports.Remove(report);

        // Save the deletion to the database.
        await _context.SaveChangesAsync();

        // Return 204 No Content to indicate that the deletion was successful.
        return NoContent();
    }

    #endregion

    #region Generate Report

    /*
     *          Functionality for generating an existing report.
     *
     *      [HttpGet("{id:int}/generate")] Allows an HTTP GET request to
     *      generate a report using its integer ID.
     *
     *      FirstOrDefaultAsync Searches the database for the report
     *      matching the supplied ID.
     *
     *      If the report does not exist, the endpoint returns 404 Not Found
     *      with an explanatory message.
     *
     *      Status Assignment Updates the report status to "Generated".
     *
     *      Date Assignment Updates the report date using the current
     *      UTC date and time through DateTime.UtcNow.
     *
     *      SaveChangesAsync Saves the updated report status and date
     *      to the database.
     *
     *      Returns 404 Not Found if the report does not exist.
     *
     *      Returns 200 OK with the updated report details when successful.
     *
     */
    [HttpGet("{id:int}/generate")]
    public async Task<IActionResult> GenerateReport(int id)
    {
        // Find the report that needs to be generated.
        var report = await _context.Reports
            .FirstOrDefaultAsync(r => r.ReportId == id);

        // Check whether the requested report exists.
        if (report == null)
        {
            return NotFound(new
            {
                message = "Report not found."
            });
        }

        // Update the report status and generation date.
        report.Status = "Generated";
        report.Date = DateTime.UtcNow;

        // Save the updated report details to the database.
        await _context.SaveChangesAsync();

        // Return 200 OK with the updated report details.
        return Ok(new
        {
            report.ReportId,
            report.ReportType,
            report.Date,
            report.GeneratedBy,
            report.Status,
            report.Description
        });
    }

    #endregion
}